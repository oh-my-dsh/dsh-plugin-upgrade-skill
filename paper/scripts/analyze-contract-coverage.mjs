// Offline analysis of archived judgments. No inference of human agreement.
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { scoreDecisions, sha256 } from '../../benchmark/report-judge/judge.mjs'
const root=fileURLToPath(new URL('../..',import.meta.url))
const audit='paper/audit/contract-review-20260917'
const archive='benchmark/results/artifacts/2026-09-15-glm-5.3-flash-unified-s16'
const raw=p=>fs.readFileSync(path.join(root,p),'utf8')
const read=p=>JSON.parse(raw(p))
const map=read(audit+'/contract-map.json')
const tasks=read(archive+'/aggregate.json').rows.map(r=>r.task).sort((a,b)=>parseInt(a.slice(1))-parseInt(b.slice(1)))
assert.equal(tasks.length,16)
const domains=Object.fromEntries(Object.entries(map.domains).map(([id,name])=>[id,{name,tasks:new Set(),arms:Object.fromEntries(['no-skill','with-skill'].map(a=>[a,{criteria:0,pass:0,partial:0,fail:0,missing:0,possible:0,awarded:0}]))}]))
const reports=[]
for(const task of tasks){
 const packetPath=`${archive}/packets/${task}.json` // run-time packet snapshot
 const packet=read(packetPath)
 assert.deepEqual(Object.keys(map.mapping[task]).sort(),packet.rubric.criteria.map(c=>c.id).sort())
 for(const arm of ['no-skill','with-skill'])for(const repeat of [1,2]){
  const reportPath=`${archive}/reports/${arm}/r${repeat}/${task}/report.md`
  const verdictPath=`${archive}/judge/${arm}/r${repeat}/${task}/verdict.json`
  const text=raw(reportPath),verdict=read(verdictPath)
  const computed=scoreDecisions(packet,{'report.md':text},verdict)
  const original=read(`${archive}/scores/${task}__${arm}__r${repeat}.json`)
  assert.equal(computed.score,original.score)
  const criteria=computed.decisions.map(c=>{
   const domain=map.mapping[task][c.id],d=domains[domain];assert.ok(d)
   d.tasks.add(task);const a=d.arms[arm];a.criteria++;a[c.verdict]++;a.possible+=c.points;a.awarded+=c.awarded
   return {...c,domain}
  })
  reports.push({task,arm,repeat,reportPath,reportSha256:sha256(text),packetPath,packetSha256:sha256(raw(packetPath)),verdictPath,verdictSha256:sha256(raw(verdictPath)),originalScore:computed.score,criteria,caps:computed.caps})
 }
}
assert.equal(reports.length,64)
assert.equal(reports.reduce((n,r)=>n+r.criteria.length,0),328)
for(const d of Object.values(domains))d.tasks=[...d.tasks].sort()
const summary={scope:'All 64 archived reports linked to 328 original rubric decisions; contract-stratified recorded judgments, not 64 independently regraded answers.',domains,reports}
const lines=['# 全量契约分层分析：64 份回答、328 项原始判分','',
'这张表覆盖整个固定实验，不挑选正向或失败案例。分类单位为原 rubric 标准的主要契约领域；同一标准只计一次。**full credit 是原 judge 的判定，不是已执行的正确性验证。** 不将此分析写成 64 份人工或 AI 独立重判。','',
'| 契约领域 | 涉及任务 | 每臂标准数 | 无 Skill 满分标准 | 有 Skill 满分标准 | 无 Skill 加权得分 | 有 Skill 加权得分 |',
'|---|---:|---:|---:|---:|---:|---:|']
const tex=[String.raw`% Generated by analyze-contract-coverage.mjs; do not edit.
\begin{table}[t]\centering\small
\begin{tabular}{p{0.37\textwidth}rrrr}
\toprule
Primary domain & Tasks & Criteria/arm & No skill & Skill\\\midrule`]
for(const d of Object.values(domains)){
 const a=d.arms['no-skill'],b=d.arms['with-skill'];assert.equal(a.criteria,b.criteria)
 lines.push(`| ${d.name} | ${d.tasks.length} | ${a.criteria} | ${a.pass}/${a.criteria} | ${b.pass}/${b.criteria} | ${(100*a.awarded/a.possible).toFixed(2)}% | ${(100*b.awarded/b.possible).toFixed(2)}% |`)
 tex.push(`${d.name} & ${d.tasks.length} & ${a.criteria} & ${a.pass} & ${b.pass} \\\\`)
}
lines.push('','各领域含不同题目和权重，不能用领域间均值比较难度；任务可能跨领域，任务数不可相加。每臂含两次重复，标准数也不等于独立样本量。',
'','10 份重点复核的局部替换敏感性保持单独报告。S6 r2 的新增全文检查在 case-notes.md 中记录，不静默扩充原先冻结的 10 份复核样本。','',
'复算：`node paper/scripts/analyze-contract-coverage.mjs --check`。结构化文件保留全部报告、rubric、verdict 的 SHA-256 和逐项原判理由。')
tex.push(String.raw`\bottomrule\end{tabular}
\caption{Complete contract-stratified analysis of the focal 64 reports. The final two columns count original full-credit criterion decisions; they are not independently validated correctness counts. Criteria/arm includes both repeats. Multi-contract criteria receive one retrospective primary label; tasks can contribute to multiple domains.}
\label{tab:contracts}\end{table}`)
const outputs={[audit+'/recorded-contracts.json']:JSON.stringify(summary,null,2)+'\n',[audit+'/README.zh.md']:lines.join('\n')+'\n','paper/generated/contract-coverage-table.tex':tex.join('\n')+'\n'}
for(const [p,s] of Object.entries(outputs)){if(process.argv.includes('--check'))assert.equal(raw(p),s);else fs.writeFileSync(path.join(root,p),s)}
console.log(lines.join('\n'))
