// paper/scripts/generate-resource-overhead-table.mjs
//
// Deterministic LaTeX rendering of benchmark/results/paired-resource-overhead.json
// (produced by benchmark/scripts/analyze-paired-resource-overhead.mjs). The
// table is intentionally narrow: it shows only within-configuration
// skill/no-skill ratios plus coverage, keeps every main group as a row, and
// renders `--` for anything the historical sources do not record.
//
// Usage:
//   node paper/scripts/generate-resource-overhead-table.mjs [--check]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const INPUT_PATH = 'benchmark/results/paired-resource-overhead.json'
export const OUTPUT_PATH = 'paper/generated/resource-overhead-table.tex'

const PLACEHOLDER = '--'

export function fmtRatio(ratio) {
  if (!ratio || ratio.status !== 'ok' || ratio.value === null || ratio.value === undefined) return PLACEHOLDER
  return `${Number(ratio.value).toFixed(2)}$\\times$`
}

export function fmtCoverage(group) {
  if (group.usageKind === 'unavailable') return 'unavailable'
  const input = group.completeness?.inputTokens
  if (!input) return PLACEHOLDER
  if (input.status === 'partial') {
    const note = input.note ?? 'partial coverage'
    return `partial (${note})`
  }
  const skill = group.arms?.skill?.recordedTrials
  const noskill = group.arms?.noskill?.recordedTrials
  if (skill !== undefined && noskill !== undefined) return `complete (${noskill} vs ${skill} trials)`
  return input.status
}

export function loadReport(repoRoot) {
  const file = join(repoRoot, INPUT_PATH)
  if (!existsSync(file)) throw new Error(`missing ${INPUT_PATH}; run \`npm run analyze:paper-resource-overhead\` first`)
  let parsed
  try {
    parsed = JSON.parse(readFileSync(file, 'utf8'))
  } catch (error) {
    throw new Error(`${INPUT_PATH}: not valid JSON (${error.message})`)
  }
  if (parsed === null || typeof parsed !== 'object') throw new Error(`${INPUT_PATH}: not an object`)
  if (parsed.schemaVersion !== 1) throw new Error(`${INPUT_PATH}: schemaVersion must be 1`)
  if (parsed.id !== 'paired-resource-overhead') throw new Error(`${INPUT_PATH}: id must be paired-resource-overhead`)
  if (!Array.isArray(parsed.groups) || parsed.groups.length === 0) throw new Error(`${INPUT_PATH}: no groups`)
  if (!Array.isArray(parsed.mainGroups) || parsed.mainGroups.length !== parsed.groups.length) {
    throw new Error(`${INPUT_PATH}: mainGroups must list every group (no silent omission)`)
  }
  return parsed
}

/** Escape the few characters that can appear in a label we render. */
export function esc(text) {
  return String(text).replaceAll('\\', '\\textbackslash{}').replaceAll('&', '\\&').replaceAll('%', '\\%').replaceAll('_', '\\_').replaceAll('#', '\\#')
}

export function renderTable(report) {
  const rows = report.groups.map((group) => [
    esc(group.label),
    fmtRatio(group.ratios?.inputTokens),
    fmtRatio(group.ratios?.outputTokens),
    fmtRatio(group.ratios?.summedTrialSeconds),
    esc(fmtCoverage(group)),
  ])
  const body = rows.map((cells) => `${cells.join(' & ')} \\\\`).join('\n')
  return [
    '% Generated by paper/scripts/generate-resource-overhead-table.mjs from',
    `% ${INPUT_PATH} — do not edit by hand; run \`npm run generate:paper-resource-overhead\`.`,
    '\\begin{table}[t]',
    '\\centering',
    '\\small',
    '\\begin{tabular}{l r r r l}',
    '\\toprule',
    'Configuration & Input & Output & Solver & Coverage \\\\',
    ' & ratio & ratio & duration & \\\\',
    '\\midrule',
    body,
    '\\bottomrule',
    '\\end{tabular}',
    '\\caption{Within-configuration resource use of the with-skill arm relative to the no-skill arm '
      + '(1.00$\\times$ = identical). Ratios are computed only inside a configuration, under that '
      + "source's own accounting convention; cached input is never added twice and the two recorded "
      + 'conventions (cached included in input vs.\\ recorded separately) are never pooled. '
      + '``Solver duration\'\' is the sum of recorded per-trial durations, not wall-clock time. '
      + 'A dash means the historical source records no machine-readable resource field for that '
      + 'configuration; it is not a zero and not an omission. Absolute token counts are not '
      + 'comparable across models, providers, or tokenizers, so the table supports no '
      + 'cross-configuration efficiency or capability ranking.}',
    '\\label{tab:resource-overhead}',
    '\\end{table}',
  ].join('\n') + '\n'
}

export function generate(repoRoot, { check = false } = {}) {
  const report = loadReport(repoRoot)
  const rendered = renderTable(report)
  const outFile = join(repoRoot, OUTPUT_PATH)
  if (check) {
    if (!existsSync(outFile)) throw new Error(`${OUTPUT_PATH} is missing; run \`npm run generate:paper-resource-overhead\``)
    if (readFileSync(outFile, 'utf8') !== rendered) throw new Error(`${OUTPUT_PATH} is out of date; run \`npm run generate:paper-resource-overhead\``)
    return { rendered, wrote: false }
  }
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, rendered)
  return { rendered, wrote: true }
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
  const check = process.argv.includes('--check')
  try {
    const result = generate(repoRoot, { check })
    console.log(check
      ? `[generate-resource-overhead-table] OK: ${OUTPUT_PATH} is up to date`
      : `[generate-resource-overhead-table] wrote ${OUTPUT_PATH} (${result.rendered.length} bytes)`)
  } catch (error) {
    console.error(`[generate-resource-overhead-table] ${error.message}`)
    process.exit(1)
  }
}
