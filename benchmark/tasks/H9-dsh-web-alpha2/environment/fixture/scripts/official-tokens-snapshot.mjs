#!/usr/bin/env node
/**
 * Snapshot the official shell's custom-property surface (--dsw-* tokens)
 * into packages/skins/skin-center/contracts/official-tokens-v1.json.
 *
 * The skin center derives automatic fallback tints for tokens a skin does
 * not remap (issue #506 follow-up); the registry pins WHICH tokens exist so
 * the derivation table never invents names the official shell does not use.
 * The static palette (--dsw-static-*) is excluded: skins must never remap
 * the palette and the fallback never targets it.
 *
 * Usage:
 *   node scripts/official-tokens-snapshot.mjs [css-file-or-dir]
 *
 * Defaults to the installed @deepseek-ai/dsh-web-frontend dist assets.
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { resolve, join, dirname } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)

function defaultCssDir() {
  try {
    const pkg = require.resolve('@deepseek-ai/dsh-web-frontend/package.json')
    return join(dirname(pkg), 'dist', 'assets')
  } catch {
    return null
  }
}

const target = process.argv[2] ?? defaultCssDir()
if (!target || !existsSync(target)) {
  console.error('official-tokens-snapshot: no css source; pass a css file/dir')
  process.exit(1)
}

const cssFiles = []
const st = statSync(target)
if (st.isFile()) cssFiles.push(target)
else if (st.isDirectory()) {
  for (const name of readdirSync(target)) {
    if (name.endsWith('.css')) cssFiles.push(join(target, name))
  }
}
if (cssFiles.length === 0) {
  console.error('official-tokens-snapshot: no css files under ' + target)
  process.exit(1)
}

const names = new Set()
for (const file of cssFiles) {
  const css = readFileSync(file, 'utf8')
  const re = /--dsw-[a-z0-9-]+/g
  for (const match of css.matchAll(re)) {
    const name = match[0]
    if (name.startsWith('--dsw-static-')) continue
    names.add(name)
  }
}

const sorted = [...names].sort()
const out = {
  $schema: 'https://schemas.linxin666.org/dsh-skin/official-tokens-v1.json',
  contractVersion: 1,
  source: 'official @deepseek-ai/dsh-web-frontend dist css',
  excludedPrefix: '--dsw-static-',
  count: sorted.length,
  tokens: sorted,
}
const dest = resolve(import.meta.dirname, '..', 'packages', 'skins', 'skin-center', 'contracts', 'official-tokens-v1.json')
writeFileSync(dest, JSON.stringify(out, null, 2) + '\n')

// The skin-center bundles the same list as a generated TS module (no fs
// access at runtime). Regenerate both together.
const tsDest = resolve(import.meta.dirname, '..', 'packages', 'skins', 'skin-center', 'src', 'core', 'css-safety', 'official-tokens.generated.ts')
const tsBody = [
  '/**',
  ' * GENERATED by scripts/official-tokens-snapshot.mjs — do not edit.',
  ' * Official shell custom-property surface (--dsw-*, static palette excluded).',
  ' */',
  'export const OFFICIAL_TOKENS: readonly string[] = [',
  ...sorted.map((name) => '  ' + JSON.stringify(name) + ','),
  ']',
  '',
].join('\n')
writeFileSync(tsDest, tsBody)
console.log('official-tokens-snapshot: wrote ' + sorted.length + ' tokens (json + generated ts)')
